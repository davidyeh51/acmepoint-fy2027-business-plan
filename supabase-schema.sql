-- 1. 南區業務機會與階段里程碑表 (50 筆：統包工程 41 案 + 資產管理 9 案)
CREATE TABLE IF NOT EXISTS public.fy2027_bu_opportunities (
    id BIGINT PRIMARY KEY,
    code TEXT NOT NULL,
    name TEXT NOT NULL,
    category TEXT NOT NULL,           -- '統包工程' | '資產管理'
    opp_type TEXT,                    -- '屋頂' | '地面' | '微電網' | '水面' | '儲能' | '銷售單'
    capacity_kwp NUMERIC(12, 3),
    total_amount BIGINT NOT NULL,
    win_rate NUMERIC(5, 4) NOT NULL,
    sign_amount BIGINT NOT NULL,
    margin_rate NUMERIC(6, 4),
    sign_margin BIGINT,
    rev_2027 BIGINT NOT NULL,
    margin_2027 BIGINT,
    defer_2028 BIGINT,
    sign_date TEXT,
    start_date TEXT,
    m_sign TEXT,
    m_permit TEXT,
    m_equip TEXT,
    m_grid TEXT,
    m_accept TEXT,
    stages_2027 INTEGER,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. 延續專案未認列與 2027 工進推估表 (13 筆)
CREATE TABLE IF NOT EXISTS public.fy2027_carryover_projects (
    id BIGINT PRIMARY KEY,
    code TEXT NOT NULL,
    name TEXT NOT NULL,
    contract_amount BIGINT,
    unrecognized_202609 BIGINT,
    est_2026_q4 BIGINT,
    est_2027 BIGINT,
    start_date TEXT,
    end_month TEXT,
    status TEXT,
    note TEXT,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. 維運預算 (O&M) 2027 明細表 (20 筆機會預估 + 128 筆 JDE 維運合約 = 148 筆)
CREATE TABLE IF NOT EXISTS public.fy2027_om_budget (
    id TEXT PRIMARY KEY,
    source_type TEXT NOT NULL,        -- '機會預估' | 'JDE維運合約'
    sub_type TEXT,                    -- '預估佔位' | '修繕專案' | '具名維運機會' | '長約基盤'
    code TEXT,
    name TEXT NOT NULL,
    margin_rate NUMERIC(6, 4),
    q1 BIGINT,
    q2 BIGINT,
    q3 BIGINT,
    q4 BIGINT,
    rev_2027 BIGINT NOT NULL,
    margin_2027 BIGINT,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. 董總決策回饋、策略推演與檔案上傳紀錄表 (Executive Notes & Simulation Snapshots)
CREATE TABLE IF NOT EXISTS public.fy2027_executive_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_name TEXT NOT NULL DEFAULT '董總決策室',
    slide_ref TEXT,                   -- 對應簡報頁次或策略模組
    strategy_tag TEXT,                -- '資產管理缺口彌平' | 'EPC勝率提拉' | '維運毛利優化' | 'AIDC第二曲線'
    content TEXT NOT NULL,
    sim_snapshot JSONB,               -- 儲存當下達標模擬器參數與推演結果
    file_url TEXT,                    -- Supabase Storage 附件網址
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- =============================================================================
-- 🔒 強制啟用 Row Level Security (RLS) 行級安全策略
-- =============================================================================
ALTER TABLE public.fy2027_bu_opportunities ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fy2027_carryover_projects ENABLE ROW LEVEL SECURITY;
